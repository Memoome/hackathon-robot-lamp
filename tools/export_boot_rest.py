"""Compile the fixed return_rest action into the lamp firmware boot target."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def render():
    source = ROOT / 'actions/return_rest.action.json'
    raw = source.read_bytes()
    action = json.loads(raw)
    assert action['action_id'] == 'return_rest' and len(action['steps']) == 1
    row = action['steps'][0]
    values = row['pulse'] + [row['base_pulse']]
    assert len(values) == 4 and all(type(v) is int and 500 <= v <= 2500 for v in values)
    assert [j['gpio'] for j in action['device_configuration']['joints']] == [12, 10, 11, 15]
    assert all(j['mode'] == 'position' for j in action['device_configuration']['joints'])
    assert row['sound'] == -1 and row['pause'] == 0
    return ('/* Generated by tools/export_boot_rest.py; do not edit. */\n#pragma once\n'
            '#define LAMP_BOOT_REST_PACKAGE_SHA256 "' + hashlib.sha256(raw).hexdigest() + '"\n'
            'static const unsigned lamp_boot_rest_pulse[4] = {' + ','.join(map(str, values)) + '};\n')

if __name__ == '__main__':
    target = ROOT / 'firmware/overlay/apps/main/boot_rest_target.h'
    target.write_text(render())
    print(target)
